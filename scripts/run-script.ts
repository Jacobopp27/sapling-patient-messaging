// Runs the Phase 1 script end to end on a fresh SQLite file, restarting (close + reopen the
// store) before step 12, and writes the transcript and final request records to docs/script-run.md.
// Usage: npm run script            (local rules mode)
//        npm run script -- --claude (Claude interpreter; needs ANTHROPIC_API_KEY)
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { claudeInterpreter } from '../server/agent/claudeInterpreter';
import { ruleInterpreter } from '../server/agent/ruleInterpreter';
import { DATA_DIR, loadClinicData } from '../server/data';
import { SCRIPT } from '../server/script';
import { ConversationService } from '../server/service';
import { Store } from '../server/store';
import type { Message } from '../server/types';

try { process.loadEnvFile('.env'); } catch { /* optional */ }
const useClaude = process.argv.includes('--claude');
const interpreter = useClaude ? claudeInterpreter : ruleInterpreter;
const file = path.join(mkdtempSync(path.join(tmpdir(), 'sapling-script-')), 'script.db');
const open = () => new ConversationService(new Store(file), loadClinicData(), interpreter);

let svc = open();
const out: string[] = [
  `# Phase 1 script run (${interpreter.name} interpreter)`,
  '',
  `Generated by \`npm run script${useClaude ? ' -- --claude' : ''}\` on a fresh SQLite file. "Now" = ${svc.store.getSettings().now}.`,
  'The store is closed and reopened from the same file before step 12 (the restart).',
  '',
];
const chip = (m: Message) => {
  const ev = (m.meta.requestEvents ?? []).map((e) => `request #${e.requestId} ${e.action}`).join(', ');
  return `_source: ${m.meta.source}${ev ? ` · ${ev}` : ''}${m.meta.trace ? ` · intent: ${(m.meta.trace.interpretation as { intent?: string })?.intent ?? 'n/a'}` : ''}_`;
};
const quote = (s: string) => s.split('\n').map((l) => `> ${l}`).join('\n');

for (const s of SCRIPT) {
  if (s.restartBefore) {
    svc.store.close();
    svc = open();
    out.push('---', '', '**Process restart** (store closed and reopened from the same file)', '');
  }
  out.push(`## Step ${s.step}`, '');
  if (s.author === 'clinic') {
    const m = svc.sendClinicMessage(s.body);
    out.push(`**Clinic #${m.id}:**`, quote(s.body), '', '_saved locally; nothing sent_', '');
    continue;
  }
  const { inbound, reply } = await svc.receivePatientMessage(s.body);
  out.push(`**Alex #${inbound.id}** (reply to #${inbound.inReplyTo}):`, quote(s.body), '', `**Agent #${reply.id}:**`, quote(reply.body), '', chip(reply), '');
}

out.push('---', '', '## Request records after the run', '', '```json', JSON.stringify(svc.store.listRequests('pt_001'), null, 2), '```', '');
const target = path.join(DATA_DIR, '..', 'docs', useClaude ? 'script-run-claude.md' : 'script-run.md');
writeFileSync(target, out.join('\n'));
console.log(out.join('\n'));
console.log(`\nWrote ${path.relative(process.cwd(), target)}`);
